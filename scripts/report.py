"""Turn the logs into docs/MEASUREMENTS.md (tables used by the technical note).

    python scripts/report.py
"""
from __future__ import annotations

import json
import statistics
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from brain.speech.listen import END_SILENCE  # noqa: E402
LOGS, OUT = ROOT / "logs", ROOT / "docs" / "MEASUREMENTS.md"


def rows(name: str) -> list[dict]:
    p = LOGS / name
    return [json.loads(l) for l in p.read_text().splitlines() if l.strip()] if p.exists() else []


def pct(v: list[float], q: float) -> float:
    v = sorted(v)
    return v[min(len(v) - 1, int(q * (len(v) - 1)))]


def stat_row(label: str, v: list[float], unit: str = "s") -> str:
    if not v:
        return f"| {label} | n/a | | | |"
    return (f"| {label} | {statistics.median(v):.2f} {unit} | {pct(v, 0.95):.2f} {unit} | "
            f"{max(v):.2f} {unit} | {len(v)} |")


def main() -> None:
    md = [f"# Measurements\n\nGenerated by `scripts/report.py` on "
          f"{time.strftime('%Y-%m-%d %H:%M')} from the files in `logs/`.\n"]

    lat = rows("latency.jsonl")
    md += ["## Spoken turn latency (end of user speech → first lamp audio)\n",
           "| Stage | Median | p95 | Max | n |", "|---|---:|---:|---:|---:|",
           f"| Endpoint (silence wait, fixed by design) | {END_SILENCE:.2f} s | | | |",
           stat_row("Speech-to-text (Whisper base.en, local)", [r["stt_s"] for r in lat]),
           stat_row("Mind (Claude, text)", [r["llm_s"] for r in lat if not r.get("image")]),
           stat_row("Mind (Claude, with camera image)", [r["llm_s"] for r in lat if r.get("image")]),
           stat_row("Text-to-speech (Piper, local)", [r["tts_s"] for r in lat]),
           stat_row("Endpoint detected → first audio", [r["endpoint_to_audio_s"] for r in lat]),
           stat_row("**Total: end of speech → audio**",
                    [r["endpoint_to_audio_s"] + END_SILENCE for r in lat]),
           f"\nTotal = {END_SILENCE} s silence wait + measured processing. Stages overlap "
           "slightly with thread hand-offs, so they do not sum exactly.\n"]

    goals = rows("goals.jsonl")
    attempts = [a for g in goals for a in g.get("attempts", []) if a.get("seen")]
    results: dict[str, int] = {}
    for g in goals:
        results[g.get("result", "?")] = results.get(g.get("result", "?"), 0) + 1
    md += ["## Goal-directed action\n",
           f"Goals run: {len(goals)} → " + ", ".join(f"{k}: {v}" for k, v in sorted(results.items())) + "\n",
           "| Metric | Median | p95 | Max | n |", "|---|---:|---:|---:|---:|",
           stat_row("Plan (vision + language)", [g["plan_s"] for g in goals if "plan_s" in g]),
           stat_row("Goal total (plan → verified)", [g["total_s"] for g in goals if g.get("total_s")]),
           stat_row("Aim error at each verification", [a["error_deg"] for a in attempts], "°"),
           stat_row("Verifications per completed goal",
                    [float(len(g["attempts"])) for g in goals if g.get("result") == "done"], ""),
           ""]
    boxed = [a for a in attempts if "on_object" in a]
    if boxed:
        md.append(f"Aim landed on the object at verification: "
                  f"{sum(a['on_object'] for a in boxed)}/{len(boxed)} checks.\n")

    et = LOGS / "engagement_test.json"
    if et.exists():
        s = json.loads(et.read_text())["summary"]
        md += ["## Engagement reliability (scripted LOOK / AWAY test)\n", "| Metric | Value |",
               "|---|---|"] + [f"| {k.replace('_', ' ')} | {v} |" for k, v in s.items()] + [""]

    res = LOGS / "resources.json"
    if res.exists():
        r = json.loads(res.read_text())
        m = r["machine"]
        md += [f"## CPU and memory ({m['system']} {m['machine']}, {m['cpus']} CPUs, "
               f"{m['ram_gb']} GB, {r['seconds']:.0f} s of active use)\n",
               "| Process | CPU mean | CPU p95 | CPU max | RSS mean | RSS max |",
               "|---|---:|---:|---:|---:|---:|"]
        for name, p in r["processes"].items():
            md.append(f"| {name} | {p['cpu_mean_pct']}% | {p['cpu_p95_pct']}% | {p['cpu_max_pct']}% | "
                      f"{p['rss_mean_mb']:.0f} MB | {p['rss_max_mb']:.0f} MB |")
        t = r["total"]
        md.append(f"\nTotal: {t['cpu_mean_pct']}% of one core on average "
                  f"(≈{t['share_of_4_cores_pct']}% of a 4-core machine), peak {t['rss_max_mb']:.0f} MB.\n")

    eng = rows("engagement.jsonl")
    if eng:
        md += [f"## Field log\n\nEngagement state changes logged in normal use: {len(eng)} "
               f"({sum(1 for e in eng if e['state'] == 'engaged')} engagements).\n"]

    OUT.write_text("\n".join(md))
    print(OUT.read_text())


if __name__ == "__main__":
    main()
